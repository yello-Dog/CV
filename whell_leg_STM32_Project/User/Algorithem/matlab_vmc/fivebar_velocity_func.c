#endif

void fivebar_velocity_func(float phi1, float phi4, float dphi1, float dphi4, float *dL0, float *dphi0)
{
    {
        float t2, t3, t4, t5, t6, t7, t8, t9, t11, t12, t13, t15, t16, t17, t18, t20, t21, t23, t24, t10, t14, t19, t22, t25, t26, t27, t29, t32, t36, t28, t31, t33, t34, t30, t35, t37, t38, t40, t39, t41, t42, t43, t44, t45, t47, t46, t48, t49, t50, t0;
        t2 = arm_cos_f32(phi1);
        t3 = arm_cos_f32(phi4);
        t4 = arm_sin_f32(phi1);
        t5 = arm_sin_f32(phi4);
        t6 = -phi4;
        t7 = t2*1.5E+1;
        t8 = t3*1.5E+1;
        t9 = -t5;
        t11 = t4*4.8E+2;
        t12 = t5*4.8E+2;
        t13 = phi1+t6;
        t15 = t2*(3.0/4.0E+1);
        t16 = t3*(3.0/4.0E+1);
        t17 = t4*(3.0/4.0E+1);
        t18 = t5*(3.0/4.0E+1);
        t20 = t2*(3.0/8.0E+1);
        t21 = t3*(3.0/8.0E+1);
        t23 = t4*(3.0/8.0E+1);
        t24 = t5*(3.0/8.0E+1);
        t10 = -t7;
        t14 = arm_sin_f32(t13);
        t19 = -t15;
        t22 = -t18;
        t25 = t4+t9;
        t26 = t25*t25;
        t27 = t14*4.5E+2;
        t29 = t8+t10+1.6E+1;
        t32 = t17+t22;
        t36 = t16+t19+2.0/2.5E+1;
        t28 = t26*2.25E+2;
        t31 = t29*t29;
        t33 = t11+t27;
        t34 = t12+t27;
        t30 = -t28;
        t35 = -t31;
        t37 = t28+t31;
        t38 = 1.0/sqrt(t37);
        t40 = t30+t35+3.136E+3;
        t39 = t38*t38*t38;
        t41 = sqrt(t40);
        t42 = 1.0/t41;
        t43 = (t32*t38*t41)/2.0;
        t44 = (t36*t38*t41)/2.0;
        t45 = t20+t21+t43;
        t47 = t23+t24+t44;
        t46 = t45*t45;
        t48 = t47*t47;
        t49 = t46+t48;
        t50 = 1.0/sqrt(t49);
        t0 = dphi1*t50*(t47*(t20+t23*t38*t41-(t33*t36*t38*t42)/4.0-(t33*t36*t39*t41)/4.0)-t45*(t23-t2*t38*t41*(3.0/8.0E+1)+(t32*t33*t38*t42)/4.0+(t32*t33*t39*t41)/4.0))-dphi4*t50*(t45*(t24+t21*t38*t41-(t32*t34*t38*t42)/4.0-(t32*t34*t39*t41)/4.0)-t47*(t21-t5*t38*t41*(3.0/8.0E+1)+(t34*t36*t38*t42)/4.0+(t34*t36*t39*t41)/4.0));
        *dL0 = t0;
    }

    {
        float t2, t3, t4, t5, t10, t6, t7, t8, t9, t11, t12, t13, t15, t16, t17, t19, t20, t21, t22, t24, t25, t27, t28, t14, t18, t23, t26, t29, t30, t31, t33, t36, t40, t32, t35, t37, t38, t34, t39, t41, t42, t44, t43, t45, t46, t47, t48, t49, t50, t51, t53, t55, t56, t52, t54, t57, t58, t0;
        t2 = arm_cos_f32(phi1);
        t3 = arm_cos_f32(phi4);
        t4 = arm_sin_f32(phi1);
        t5 = arm_sin_f32(phi4);
        t10 = -phi4;
        t6 = t2*3.0;
        t7 = t3*3.0;
        t8 = t4*3.0;
        t9 = t5*3.0;
        t11 = t2*1.5E+1;
        t12 = t3*1.5E+1;
        t13 = -t5;
        t15 = t4*4.8E+2;
        t16 = t5*4.8E+2;
        t17 = phi1+t10;
        t19 = t2*(3.0/4.0E+1);
        t20 = t3*(3.0/4.0E+1);
        t21 = t4*(3.0/4.0E+1);
        t22 = t5*(3.0/4.0E+1);
        t24 = t2*(3.0/8.0E+1);
        t25 = t3*(3.0/8.0E+1);
        t27 = t4*(3.0/8.0E+1);
        t28 = t5*(3.0/8.0E+1);
        t14 = -t11;
        t18 = arm_sin_f32(t17);
        t23 = -t19;
        t26 = -t22;
        t29 = t4+t13;
        t30 = t29*t29;
        t31 = t18*4.5E+2;
        t33 = t12+t14+1.6E+1;
        t36 = t21+t26;
        t40 = t20+t23+2.0/2.5E+1;
        t32 = t30*2.25E+2;
        t35 = t33*t33;
        t37 = t15+t31;
        t38 = t16+t31;
        t34 = -t32;
        t39 = -t35;
        t41 = t32+t35;
        t42 = 1.0/sqrt(t41);
        t44 = t34+t39+3.136E+3;
        t43 = t42*t42*t42;
        t45 = sqrt(t44);
        t46 = 1.0/t45;
        t47 = t36*t42*t45*4.0E+1;
        t48 = (t36*t42*t45)/2.0;
        t49 = t40*t42*t45*4.0E+1;
        t50 = (t40*t42*t45)/2.0;
        t51 = t6+t7+t47;
        t53 = t8+t9+t49;
        t55 = t24+t25+t48;
        t56 = t27+t28+t50;
        t52 = t51*t51;
        t54 = t53*t53;
        t57 = t52+t54;
        t58 = 1.0/t57;
        t0 = dphi1*t58*(t55*(t24+t27*t42*t45-(t37*t40*t42*t46)/4.0-(t37*t40*t43*t45)/4.0)+t56*(t27-t2*t42*t45*(3.0/8.0E+1)+(t36*t37*t42*t46)/4.0+(t36*t37*t43*t45)/4.0))*6.4E+3+dphi4*t58*(t56*(t28+t25*t42*t45-(t36*t38*t42*t46)/4.0-(t36*t38*t43*t45)/4.0)+t55*(t25-t5*t42*t45*(3.0/8.0E+1)+(t38*t40*t42*t46)/4.0+(t38*t40*t43*t45)/4.0))*6.4E+3;
        *dphi0 = t0;
    }

}
